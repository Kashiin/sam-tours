// Merges numbered translations into js/i18n/<lang>.strings.js.
//   node scripts/i18n-merge.js <lang> <translations.txt>
// Lines of translations.txt are "NNNN<TAB>text", where NNNN is the line number of the source string in
// i18n-missing.json (as written by `i18n-extract.js --missing`) and " ⏎ " marks a line break.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const [lang, file] = process.argv.slice(2);
if (!lang || !file) throw new Error('usage: node scripts/i18n-merge.js <lang> <translations.txt>');

const source = JSON.parse(readFileSync('i18n-missing.json', 'utf8'))[lang];
const target = `js/i18n/${lang}.strings.js`;
const strings = existsSync(target) ? (await import(`../${target}?${Date.now()}`)).default : {};

let added = 0;
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^(\d{4})\t(.+)$/);
  if (!m) continue;
  const key = source[Number(m[1])];
  if (key === undefined) throw new Error('unknown index ' + m[1]);
  const value = m[2].trim().replace(/\s*⏎\s*/g, '\n');
  if (key.split('\n').length !== value.split('\n').length) console.warn(`line breaks differ at ${m[1]}`);
  strings[key] = value;
  added++;
}

const sorted = Object.fromEntries(Object.entries(strings).sort(([a], [b]) => a.localeCompare(b, 'ru')));
writeFileSync(
  target,
  `// Generated by scripts/i18n-merge.js: Russian source text -> ${lang}.\nexport default ${JSON.stringify(sorted, null, 1)};\n`,
);
console.log(`${lang}: +${added}, total ${Object.keys(sorted).length}`);
